// ---- Helper functions ----

export function getPublishedPosts(): BlogPost[] {
  return blogPosts
    .filter((post) => post.published)
    .sort(
      (a, b) =>
        new Date(b.published_at).getTime() - new Date(a.published_at).getTime(),
    );
}

export function getPostBySlug(slug: string): BlogPost | undefined {
  return blogPosts.find((post) => post.slug === slug && post.published);
}

export function getAllPostSlugs(): string[] {
  return blogPosts.filter((p) => p.published).map((p) => p.slug);
}

export function getPostsByCategory(category: string): BlogPost[] {
  return getPublishedPosts().filter(
    (post) => post.category.toLowerCase() === category.toLowerCase(),
  );
}

export function getAllCategories(): string[] {
  const categories = getPublishedPosts().map((post) => post.category);
  return [...new Set(categories)];
}

export function getAllTags(): string[] {
  const tags = getPublishedPosts().flatMap((post) => post.tags);
  return [...new Set(tags)];
}

export function getRelatedPosts(
  currentSlug: string,
  limit = 3,
): BlogPost[] {
  const current = getPostBySlug(currentSlug);
  if (!current) return [];

  return getPublishedPosts()
    .filter((post) => post.slug !== currentSlug)
    .map((post) => ({
      post,
      score:
        (post.category === current.category ? 2 : 0) +
        post.tags.filter((tag) => current.tags.includes(tag)).length,
    }))
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map(({ post }) => post);
}
